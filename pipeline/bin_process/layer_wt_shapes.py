# 为了向后兼容，提供一个函数来获取按顺序排列的 shapes 列表
def get_wt_shapes_list() -> list[tuple[int, int, int, int]]:
    """
    返回按顺序排列的 WT shapes 列表（向后兼容）
    
    注意：这个函数返回的顺序可能与原始列表不完全一致，
    因为字典是无序的。如果需要特定顺序，请使用层名直接访问。
    """
    # 按照层名排序（L{xx}_s{xx} 格式）
    sorted_keys = sorted(WT_SHAPES.keys(), key=lambda x: (
        int(x.split('_')[0][1:]) if x[0] == 'L' else 999,
        int(x.split('_')[1][1:]) if len(x.split('_')) > 1 and x.split('_')[1][0] == 's' else 0
    ))
    return [WT_SHAPES[key] for key in sorted_keys]


def get_wt_shape(layer_name: str) -> tuple[int, int, int, int] | None:
    """
    根据层名获取 WT shape
    
    Args:
        layer_name: 层名，格式为 "L{xx}_s{xx}" 或 "L{xx}_s{xx}_conv_wt" 等
    
    Returns:
        shape 元组 (out_ch, in_ch, kernel_h, kernel_w)，如果找不到则返回 None
    
    Examples:
        >>> get_wt_shape("L02_s00")
        (192, 160, 1, 1)
        >>> get_wt_shape("L02_s00_conv_wt")
        (192, 160, 1, 1)
    """
    # 提取层标识（L{xx}_s{xx}）
    if '_conv_wt' in layer_name:
        layer_name = layer_name.replace('_conv_wt', '')
    if '_conv_bn' in layer_name:
        layer_name = layer_name.replace('_conv_bn', '')
    
    # 直接查找
    if layer_name in WT_SHAPES:
        return WT_SHAPES[layer_name]
    
    # 如果找不到，返回 None
    return None


def get_bn_channels(layer_name: str) -> int | None:
    """
    根据层名获取 BN 通道数（等于对应 WT 层的 out_ch）
    
    Args:
        layer_name: BN 层名，格式为 "L{xx}_s{xx}_conv_bn" 或 "L{xx}_s{xx}"
    
    Returns:
        BN 通道数（等于对应 WT 层的 out_ch），如果找不到则返回 None
    
    Examples:
        >>> get_bn_channels("L02_s00_conv_bn")
        192
    """
    shape = get_wt_shape(layer_name)
    if shape:
        return shape[0]  # out_ch
    return None


